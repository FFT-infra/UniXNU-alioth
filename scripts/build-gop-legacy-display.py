#!/usr/bin/env python3
"""Bind the owned GOP backend to the unchanged original Legacy lifecycle, for alioth.

This is UniXNU-sheng's scripts/build-gop-legacy-display.py with the board coupling removed. The
sheng script compiles the whole peripheral fleet into the same archive (touch, Wi-Fi, audio DSP,
backlight, battery, buttons, HID, key store, UFS log writer, reset probe), each of which pulls in
its own board kit and driver directories. alioth has none of those yet, and a display archive that
also carries them cannot be linked until they do, so this script builds the display path alone:

  drivers/GopFramebuffer/NativeLegacyDisplay.cpp   the owned backend
  drivers/GopFramebuffer/NativeGOPPresenter.cpp    the owned presenter
  package/LegacyDisplayProbe.cpp                   the board half (hooks and the two entries)
  build/native-legacy-display/original-bindings.S  absolute bindings to the prelinked family

The class layout, the vtable order and every absolute address are still verified against the
kernel this build links into, exactly as in sheng, because the original family is prelinked in
both kernels rather than exported. A mismatch fails the build instead of producing a silently
wrong archive.
"""
import hashlib
import json
import os
from pathlib import Path
import struct
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'build/native-legacy-display'
OUT.mkdir(parents=True, exist_ok=True)
sys.path.insert(0, str(ROOT / 'kits/XnuPrelink'))
from native_prelink import macho, backed_offset, exports


def run(cmd, **kw):
	return subprocess.check_output([str(x) for x in cmd], timeout=90, **kw)


def require(value, message):
	if not value:
		raise SystemExit(message)


def sha(path):
	return hashlib.sha256(Path(path).read_bytes()).hexdigest()


# The device package is linked into the tree as kits/<kit>, while `package/` is the shared one,
# so locate this board's half the way scripts/build-boot-progress.py does.
packages = sorted(ROOT.glob('kits/*/LegacyDisplayProbe.cpp'))
require(len(packages) == 1, 'Expected one device package with LegacyDisplayProbe.cpp')
PROBE_SOURCE = packages[0]


# The audit re-derives the class ABI from the kernel image itself. It also refreshes
# build/display-analysis/mobile-graphics-legacy-abi.json, which supplies the slot table below.
print(run(['python3', ROOT / 'scripts/audit-mobile-graphics-legacy.py'], text=True), end='')
audit = json.loads((ROOT / 'build/display-analysis/mobile-graphics-legacy-abi.json').read_text())
pure = audit['abstract_slots']
methods = audit['methods']

# Opaque ABI storage for the exact original class, not source-level access to its private
# fields. Only qualified base prototypes may be called from source; the rest are dispatch
# targets the original vtable reaches.
header = '''// SPDX-License-Identifier: BSD-2-Clause-Patent
// Generated by scripts/build-gop-legacy-display.py. Do not edit.
#pragma once
#include <IOKit/IOService.h>
#include <libkern/libkern.h>
struct OriginalLegacySwapRequest;
class IOMobileFramebufferLegacy : public IOService {
 OSDeclareAbstractStructors(IOMobileFramebufferLegacy)
 unsigned char originalPrivate[0x18a0-sizeof(IOService)];
public:
 // Both fields are qualified by the complete original slot-249 getter.
 // This modifies this object's own mode state, never a vtable or executable.
 void installBootDimensions(uint32_t width,uint32_t height) {
  *reinterpret_cast<uint32_t *>(reinterpret_cast<unsigned char *>(this)+5808)=width;
  *reinterpret_cast<uint32_t *>(reinterpret_cast<unsigned char *>(this)+5812)=height;
 }
 const OriginalLegacySwapRequest *pendingSwapRequest() const {
  const OriginalLegacySwapRequest *request=nullptr;
  memcpy(&request,reinterpret_cast<const unsigned char *>(this)+5480,sizeof(request));return request;
 }
 // The queue is a tail queue (head at +5480, tail pointer at +5488, each request's next at +2960
 // and previous-link at +2968). Taking the head moves the next request up if a client already
 // queued one behind it, and the original queue's reference moves to the current-swap slot.
 bool activateOnlyPendingSwap(const OriginalLegacySwapRequest *request) {
  auto self=reinterpret_cast<unsigned char *>(this);
  auto bytes=reinterpret_cast<const unsigned char *>(request);
  const void *current=nullptr,*head=nullptr,*tail=nullptr,*next=nullptr,*previous=nullptr;
  memcpy(&current,self+5472,8);memcpy(&head,self+5480,8);memcpy(&tail,self+5488,8);
  if(!request || current || head!=request)return false;
  memcpy(&next,bytes+2960,8);memcpy(&previous,bytes+2968,8);
  if(previous!=self+5480)return false;
  if(next) {
   const void *link=self+5480;
   memcpy(const_cast<unsigned char *>(reinterpret_cast<const unsigned char *>(next))+2968,&link,8);
  } else if(tail!=bytes+2960)return false;
  memcpy(self+5472,&request,8);
  if(next) {memcpy(self+5480,&next,8);}
  else {const void *empty=nullptr,*emptyTail=self+5480;memcpy(self+5480,&empty,8);memcpy(self+5488,&emptyTail,8);}
  return true;
 }
 void free() override;
 bool init(OSDictionary *properties=nullptr) override;
 IOReturn setProperties(OSObject *) override;
 void systemWillShutdown(IOOptionBits) override;
 IOService *probe(IOService *,SInt32 *) override;
 bool start(IOService *) override;
 void stop(IOService *) override;
 IOWorkLoop *getWorkLoop() const override;
 IOReturn newUserClient(task_t,void *,UInt32,IOUserClient **) override;
 IOReturn setPowerState(unsigned long,IOService *) override;
'''
for i in range(168, 358):
	if i == 184:
		header += ' virtual bool isMainDisplay();\n'
	elif i == 188:
		header += ' virtual IOReturn getDotPitch(uint32_t *);\n'
	elif i == 213:
		header += ' virtual IOReturn supportedFrameInfo(uint32_t,uint32_t *,char *,uint32_t *)=0;\n'
	elif i == 249:
		header += ' virtual void getDisplayDimensions(uint32_t *,uint32_t *);\n'
	elif i == 290:
		header += ' virtual void kickSwapQueue();\n'
	elif i == 296:
		header += ' virtual bool validateSwap(const OriginalLegacySwapRequest *);\n'
	elif i == 295:
		header += ' virtual void completeCurrentSwap();\n'
	elif i == 337:
		header += ' virtual IOReturn collectCompletionReports(uint32_t,void *,uint32_t *,uint32_t)=0;\n'
	elif i == 288:
		header += ' virtual bool startHardware();\n'
	elif i == 301:
		header += ' virtual bool getRefreshAttributes(uint64_t *,bool);\n'
	elif i in pure:
		header += f' virtual __attribute__((noreturn)) void opaque{i}()=0;\n'
	else:
		header += f' virtual __attribute__((deprecated("Unclassified ABI: never call from source"))) void opaque{i}();\n'
header += '};\nstatic_assert(sizeof(IOMobileFramebufferLegacy)==0x18a0,"Actual original instance extent");\n'
(OUT / 'OriginalLegacyFramebufferABI.h').write_text(header)

# The owned backend, compiled with the kernel's own flags through the generic driver recipe.
print(run(['python3', ROOT / 'scripts/build-arm-driver.py', 'NativeLegacyDisplay'], text=True), end='')
obj = OUT / 'NativeLegacyDisplay.o'
require(obj.is_file(), 'The driver recipe did not leave NativeLegacyDisplay.o in build/native-legacy-display')

# Recover the owned vtable in slot order and require every one of the 358 entries to be a real
# relocation: an unrelocated entry would mean the class no longer overrides the whole layout.
raw = obj.read_bytes()
image = macho(raw)
symbol_table = next(p for c, p, _ in image['commands'] if c == 2)
symbols_at, count, strings, _ = struct.unpack_from('<4I', raw, symbol_table + 8)
symbols = []
for i in range(count):
	index, kind, section, _, address = struct.unpack_from('<IBBHQ', raw, symbols_at + i * 16)
	symbols.append((raw[strings + index:raw.index(b'\0', strings + index)].decode(), address, kind))
vtable = next(address for name, address, _ in symbols if name == '__ZTV19NativeLegacyDisplay')
relocations = {}
for segment in image['segments']:
	for section in segment['sections']:
		if section['va'] <= vtable < section['va'] + section['size']:
			relocation_offset, relocation_count = struct.unpack_from('<2I', raw, section['command_offset'] + 56)
			for i in range(relocation_count):
				offset, bits = struct.unpack_from('<2I', raw, relocation_offset + i * 8)
				if bits >> 27 & 1 and bits >> 28 == 0 and bits >> 25 & 3 == 3:
					relocations[section['va'] + offset] = symbols[bits & 0xffffff][0]
compiled = [relocations.get(vtable + 16 + i * 8) for i in range(358)]
require(all(compiled) and vtable + 16 + 358 * 8 not in relocations, 'Exact owned 358-entry vtable')

# The reference candidate is the kernel this build links into: the family is prelinked there, so
# its vtable, constructors and slot bodies are read out of the image rather than from a symbol.
candidate = ROOT / 'build/xnu-prelink/native-owner-mobile-graphics-candidate.macho'
if not candidate.exists():
	later = sorted((ROOT / 'build/xnu-prelink').glob('native-owner-ufs-cpu-desktop-*-candidate.macho'),
	               key=lambda f: f.stat().st_mtime)
	require(later, 'No reference candidate available')
	candidate = later[-1]
original = candidate.read_bytes()
original_image = macho(original)
names = {name: address for address, group in exports(original, original_image).items() for name in group}


def read(address, length):
	at = backed_offset(original_image['segments'], address, length, len(original))
	return original[at:at + length]


bindings = {
	'__ZN25IOMobileFramebufferLegacyC2EPK11OSMetaClass': 0xfffffff0057865cc,
	'__ZN25IOMobileFramebufferLegacyD2Ev': 0xfffffff005786618,
	'__ZN25IOMobileFramebufferLegacy10gMetaClassE': 0xfffffff006b35940,
	'__ZTV25IOMobileFramebufferLegacy': int(audit['legacy_vptr'], 16) - 16,
}
owned, native = [], []
for i, name in enumerate(compiled):
	expected = int(methods[i]['address'], 16)
	if name.startswith(('__ZN19NativeLegacyDisplay', '__ZNK19NativeLegacyDisplay')):
		owned.append(i)
		require(i in (0, 1, 7, 14, 84, 86, 87, 141, 155, 184, 188, 288, 290, 296, 301) or i in pure,
		        'Only qualified own methods and guarded leaves override')
	elif '25IOMobileFramebufferLegacy' in name:
		require(i not in pure, 'No unresolved original abstract backend target')
		bindings[name] = expected
	else:
		require(i < 168 and names.get(name) == expected, 'Actual inherited native base symbol ' + str(i))
		native.append(i)
require(owned == sorted([0, 1, 7, 14, 84, 86, 87, 141, 155, 184, 188, 288, 290, 296, 301] + pure),
        'Exact owned method set')
undefined = {name for name, _, kind in symbols if kind == 1 and 'IOMobileFramebufferLegacy' in name}
require(undefined == set(bindings), 'All and only actual original-class imports qualified')

# Exact original IOSurface getters, independently observed through the real original swap
# request. These aliases call original code; no object layout is substituted.
for name, address, field, wide in [
    ('descriptor', 0xfffffff004b9ead0, 48, True), ('width', 0xfffffff004b9ebbc, 88, True),
    ('height', 0xfffffff004b9ebc4, 96, True), ('stride', 0xfffffff004b9ebd4, 104, True),
    ('allocation', 0xfffffff004b9ebfc, 144, True), ('format', 0xfffffff004b9ebac, 128, False),
    ('planes', 0xfffffff004b9ebf4, 152, False)]:
	expected = (0xf9400000 if wide else 0xb9400000) | ((field // (8 if wide else 4)) << 10)
	require(read(address, 8) == struct.pack('<2I', expected, 0xd65f03c0), 'Exact original surface getter ' + name)
	bindings['_native_legacy_surface_' + name] = address

# The original display-refresh notification sender (self, timestamp, continuous host time, frame
# interval): it sends the six-word vsync message (type 5) to every client entry queued at +5592.
require(read(0xfffffff005796720, 16) == bytes.fromhex('ff0302d1fd7b07a9fdc30191a0831ff8') and
        read(0xfffffff005796830, 4) == bytes.fromhex('08ed4af9') and
        read(0xfffffff00579685c, 16) == bytes.fromhex('e2230091c3008052240080521684ff97') and
        read(0xfffffff005795fbc, 4) == bytes.fromhex('0ab182d2'),
        'Original vsync sender, its +5592 queue and six-word drop-allowed async send')
bindings['_native_legacy_vsync_notify'] = 0xfffffff005796720

# Slot 301 fills the six refresh words that setDisplayRefreshProperties publishes as
# IOMFBDisplayRefresh; the generic body fixes the minimum at 0x04444444 (1/60 s).
require(int(methods[301]['address'], 16) == 0xfffffff00579ea5c and
        read(0xfffffff00579ea68, 8) == bytes.fromhex('888888d28888a0f2') and
        read(0xfffffff00579ec54, 4) == bytes.fromhex('08b544f9'),
        'Original slot-301 refresh words with the 1/60 s minimum')
require(read(0xfffffff00579ebb8, 16) == bytes.fromhex('ff0302d1fd7b07a9fdc30191a0031ff8') and
        read(0xfffffff00579ed54, 16) == bytes.fromhex('086540f90173ff90218c0c9100013fd6'),
        'Original setDisplayRefreshProperties publishing IOMFBDisplayRefresh')
bindings['_native_legacy_set_refresh_properties'] = 0xfffffff00579ebb8


def branch(pc):
	word = struct.unpack('<I', read(pc, 4))[0]
	require(word & 0xfc000000 == 0x94000000, 'Actual protected base call')
	value = word & 0x3ffffff
	return pc + 4 * (value - (1 << 26) if value & (1 << 25) else value)


require(branch(0xfffffff0057865fc) == 0xfffffff00577b510 and branch(0xfffffff005786630) == 0xfffffff00577b55c,
        'Original protected Legacy C2/D2 really call their original Service bases')
require(read(0xfffffff005787ef8, 16) == bytes.fromhex('080040f9088144f900013fd6e0000037'),
        'Original bool start_hardware() call and result check')
getter = int(methods[249]['address'], 16)
for offset, field in [(0x30, 5808), (0x58, 5812)]:
	require(struct.unpack('<I', read(getter + offset, 4))[0] == 0xb9400000 | ((field // 4) << 10) | (8 << 5) | 8,
	        'Actual original width/height getter fields')
require(int(methods[295]['address'], 16) == 0xfffffff005795b88 and
        read(0xfffffff005795b98, 16) == bytes.fromhex('e00740f9280080520101001272d3ff97'),
        'Actual original slot-295 passes true to the normal current completion body')
require(read(0xfffffff00578aa7c, 24) == bytes.fromhex('080040f9084545f9030080d2e20303aa0400805200013fd6'),
        'Original completion calls optional report slot 337 with null outputs and zero limit')
require(read(0xfffffff005777e9c, 16) == bytes.fromhex('080040f908e142f900013fd6c0000036'),
        'Original isMainDisplay dispatch uses only self and tests boolean bit zero')

assembly = OUT / 'original-bindings.S'
assembly.write_text(''.join(f'.globl {name}\n.set {name}, {va:#x}\n' for name, va in sorted(bindings.items())))
sdk = run(['xcrun', '--sdk', 'iphoneos', '--show-sdk-path'], text=True).strip()
run(['xcrun', 'clang', '-target', 'arm64-apple-ios17.0', '-isysroot', sdk, '-c', assembly,
     '-o', OUT / 'original-bindings.o'])

# The owned object's static initializer has to run from the board probe between preModLoad and
# postModLoad, not from the kernel's __mod_init_func. Moving it out must not touch any code.
llvm = Path(run(['xcrun', '--find', 'llvm-objcopy'], text=True).strip()).parent
late = OUT / 'NativeLegacyDisplay.late.o'
run([llvm / 'llvm-objcopy', '--remove-section=__DATA,__mod_init_func',
     '--globalize-symbol=__GLOBAL__sub_I_NativeLegacyDisplay.cpp', obj, late])


def code(data, info):
	section = next(s for g in info['segments'] for s in g['sections'] if s['name'] == '__text')
	return data[section['fileoff']:section['fileoff'] + section['size']]


require(code(raw, image) == code(late.read_bytes(), macho(late.read_bytes())),
        'Only owned initializer section registration changes')

# The board half is C++ and subclasses an owned class, so it compiles with the kernel's C++
# recipe, the same one scripts/build-arm-driver.py replays. It reaches BSD and IOKit, hence the
# general-register restriction and the explicit osfmk include.
record = json.loads((ROOT / 'build/xnu/ios-obj/DEVELOPMENT_ARM64_BCM2837/iokit/DEVELOPMENT/IOPlatformExpert.cpo.json')
                    .read_text().strip().rstrip(','))
probe_source = PROBE_SOURCE
probe_obj = OUT / 'LegacyDisplayProbe.o'
# Compile from a private copy on local disk. Reading the source straight off the virtiofs mount
# makes clang-24 abort with `MemoryBuffer::init: Buffer is not null terminated` when the shared
# directory's cached size and content disagree for a moment, which happens while this workspace
# is edited from the other side. The copy pins one consistent inode; the hash check below proves
# it is the same file the report records.
import shutil
import tempfile
staged = Path(tempfile.mkdtemp(prefix='unixnu-legacy-probe-')) / 'LegacyDisplayProbe.cpp'
shutil.copyfile(probe_source, staged)
if sha(staged) != sha(probe_source):
	raise SystemExit(f'{probe_source} changed while it was copied for compilation; rerun the build')
probe_source = staged
command, arguments, i = [], record['arguments'], 0
suppressions = []
while i < len(arguments):
	value = arguments[i]
	if value == record['file']:
		command.append(str(probe_source))
	elif value == '-o':
		command += ['-o', str(probe_obj)]
		i += 1
	elif value == '-Xclang' and arguments[i + 1].startswith('-W'):
		i += 1
	elif value.startswith('-Wno-'):
		# The flags below set this script's own strictness, so the record's warning switches are
		# dropped. Its suppressions are not strictness: XNU's own headers are written against
		# them, and -Wextra turns several of those diagnostics on, which fails the build inside
		# kalloc.h, vm_kern.h and IOLib.h on code this board does not own. Keep them, and append
		# them after the flags below so they win.
		suppressions.append(value)
	elif not value.startswith(('-W', '-DXNU_BOOT_PROGRESS=')):
		command.append(value)
	i += 1
command += ['-mgeneral-regs-only', '-Wall', '-Wextra', '-Werror', '-Wno-unused-parameter',
            '-Wno-unnecessary-virtual-specifier', '-Wno-c99-designator', '-Wno-reorder-init-list',
            '-Wno-deprecated-enum-enum-conversion',
            # `-I .` in the replayed recipe means the recorded object directory, so it resolves
            # meta_features.h only while the compiler runs there. Name the directory explicitly
            # as well, so the include does not depend on the working directory alone.
            '-I', str(record['directory']),
            '-I', str(ROOT / '.cache/xnu-work/osfmk'), '-I', str(OUT)]
command += suppressions
run(command, cwd=record['directory'])
(OUT / 'probe-compile-command.json').write_text(json.dumps(command, indent=2) + '\n')

# The CPU frequency control, compiled with the same record so its flags match the kernel.
# It exports sheng_cpufreq_probe/sheng_cpufreq_poll, which BootProgress weak-imports and
# calls from its monitor loop.
# The device package appears in the tree as kits/<kit>; tree/package is the upstream one.
# Same lookup build-boot-progress.py uses for its board sources.
_cpufreq = sorted(ROOT.glob('kits/*/CpuFreqProbe.cpp'))
require(_cpufreq, 'cpu frequency probe missing: no kits/*/CpuFreqProbe.cpp')
cpufreq_source = _cpufreq[0]
cpufreq_obj = OUT / 'CpuFreqProbe.o'
cpufreq_command, suppressions2, i = [], [], 0
while i < len(arguments):
    value = arguments[i]
    if value == record['file']:
        cpufreq_command.append(str(cpufreq_source))
    elif value == '-o':
        cpufreq_command += ['-o', str(cpufreq_obj)]
        i += 1
    elif value == '-Xclang' and arguments[i + 1].startswith('-W'):
        i += 1
    elif value.startswith('-Wno-'):
        suppressions2.append(value)
    elif not value.startswith(('-W', '-DXNU_BOOT_PROGRESS=')):
        cpufreq_command.append(value)
    i += 1
cpufreq_command += ['-mgeneral-regs-only', '-Wall', '-Wextra', '-Werror', '-Wno-unused-parameter',
                    '-Wno-c99-designator', '-Wno-reorder-init-list',
                    '-Wno-deprecated-enum-enum-conversion', '-Wno-missing-designated-field-initializers',
                    '-I', str(record['directory']), '-I', str(ROOT / '.cache/xnu-work/osfmk'), '-I', str(OUT)]
cpufreq_command += suppressions2
run(cpufreq_command, cwd=record['directory'])

# The owned presenter, staged the same way.
print(run(['python3', ROOT / 'scripts/build-arm-driver.py', 'NativeGOPPresenter'], text=True), end='')
presenter = ROOT / 'build/native-gop-presenter/NativeGOPPresenter.o'
require(presenter.is_file(), 'The driver recipe did not leave NativeGOPPresenter.o in build/native-gop-presenter')
presenter_late = OUT / 'NativeGOPPresenter.late.o'
run([llvm / 'llvm-objcopy', '--remove-section=__DATA,__mod_init_func',
     '--globalize-symbol=__GLOBAL__sub_I_NativeGOPPresenter.cpp', presenter, presenter_late])
require(code(presenter.read_bytes(), macho(presenter.read_bytes())) ==
        code(presenter_late.read_bytes(), macho(presenter_late.read_bytes())),
        'Owned presenter instructions unchanged by late init staging')

# The HID publisher belongs in this archive and nowhere else. ShengHidInput's own recipe
# produces NativeHidInput.late.o and hid-original-bindings.o but only into its build
# directory; nothing in the generic archive pipeline picks a ``.late.o`` up, and a plain
# archive is not force-loaded, so an object with no inbound reference is dropped at link
# time. That is what earlier images did: the touch core ran, contacts reached the host, and
# the kernel carried no IOHIDDevice at all. UniXNU-sheng wires it the same way, from its own
# display recipe, because this archive is the one the kernel link force-loads.
#
# Two inputs are adapted for this board rather than taken from sheng:
#   * the reference candidate: sheng's recipe accepts "any later candidate built from the
#     same original components", but looks for it under sheng's own pipeline name. This tree
#     names its candidate after the profile that produced it, so publish ours under the name
#     the recipe globs. The recipe still verifies the original IOHIDFamily instruction hash
#     and the whole 207-slot ABI against it, so nothing is taken on trust.
#   * ``brew --prefix llvm``: the recipe locates llvm-objcopy through Homebrew, which does
#     not exist on the Linux builder. Point it at the llvm that is on PATH instead.
hid_dir = ROOT / 'build/sheng-hid-input'
hid = subprocess.run(['python3', ROOT / 'scripts/build-sheng-hid-input.py'],
                     capture_output=True, text=True)
print(hid.stdout, end='')
require(hid.returncode == 0, 'build-sheng-hid-input.py failed: ' + (hid.stderr or hid.stdout)[-1200:])

archive = OUT / 'libNativeLegacyDisplay.late.a'
archive.unlink(missing_ok=True)
run(['xcrun', 'ar', 'rcs', archive, late, OUT / 'original-bindings.o', probe_obj, cpufreq_obj, presenter_late,
     hid_dir / 'NativeHidInput.late.o', hid_dir / 'hid-original-bindings.o'])

sources = [ROOT / 'drivers/GopFramebuffer/NativeLegacyDisplay.cpp',
           ROOT / 'drivers/GopFramebuffer/NativeLegacyRequest.h',
           ROOT / 'drivers/GopFramebuffer/NativeGOPPresenter.cpp',
           ROOT / 'drivers/GopFramebuffer/NativeGOPWire.h',
           ROOT / 'drivers/GopFramebuffer/OriginalMobileFramebufferABI.h',
           # The board half by its repository path, not the staged copy: the two hashes were
           # proved equal before the compile, so the report names the file a reader can inspect.
           PROBE_SOURCE, OUT / 'OriginalLegacyFramebufferABI.h']
(OUT / 'build-report.json').write_text(json.dumps(dict(
    source_sha256={str(path.relative_to(ROOT)): sha(path) for path in sources},
    original_candidate_sha256=sha(candidate),
    original_audit_sha256=sha(ROOT / 'build/display-analysis/mobile-graphics-legacy-abi.json'),
    compiled_object_sha256=sha(obj), late_object_sha256=sha(late),
    probe_object_sha256=sha(probe_obj), presenter_object_sha256=sha(presenter_late),
    archive_sha256=sha(archive),
    bindings={name: hex(value) for name, value in bindings.items()},
    virtual_entries=358, owned_entries=owned, inherited_native_entries=native,
    guarded_backend_leaves=[i for i in pure if i not in (213, 337)],
    original_instructions_modified=False, driver_initialized=False,
    display_presented=False, desktop=False), indent=2) + '\n')
print('Built genuine original Legacy inheritance/dispatch for alioth; seven backend leaves still '
      'guarded, runtime lifecycle unqualified')
